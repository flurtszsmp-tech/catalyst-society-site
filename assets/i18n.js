(function () {
  var KUNCI = 'catalyst-lang';
  var kamus = window.CATALYST_I18N;

  function bahasaAwal() {
    try { var s = localStorage.getItem(KUNCI); if (s && kamus[s]) return s; } catch (e) {}
    var n = (navigator.language || 'id').slice(0, 2).toLowerCase();
    if (n === 'zh') return 'zh';
    if (n === 'en') return 'en';
    return 'id';
  }

  window.terapkanBahasa = function (kode) {
    var k = kamus[kode] || kamus.id;
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var teks = k[el.dataset.i18n];
      if (teks != null) el.innerHTML = teks;
    });
    document.documentElement.lang = kode === 'zh' ? 'zh-CN' : kode;
    document.querySelectorAll('[data-lang]').forEach(function (b) {
      b.classList.toggle('on', b.dataset.lang === kode);
    });
    var tampil = document.getElementById('langAktif');
    if (tampil) tampil.textContent = kode.toUpperCase();
    var bendera = document.getElementById('langBendera');
    if (bendera) {
      var pakai = bendera.querySelector('use');
      if (pakai) pakai.setAttribute('href', '#f-' + (kamus[kode] ? kode : 'id'));
    }
    try { localStorage.setItem(KUNCI, kode); } catch (e) {}
    /* innerHTML setiap teks baru saja ditimpa. Halaman yang memecah judul
       menjadi baris beranimasi perlu membentuknya ulang sesudah ini. */
    document.dispatchEvent(new CustomEvent('bahasa-berubah', { detail: kode }));
  };

  document.addEventListener('DOMContentLoaded', function () {
    terapkanBahasa(bahasaAwal());
    document.querySelectorAll('[data-lang]').forEach(function (b) {
      b.addEventListener('click', function () { terapkanBahasa(b.dataset.lang); });
    });
    var pemicu = document.getElementById('langBtn');
    var menu = document.getElementById('langMenu');
    if (pemicu && menu) {
      pemicu.addEventListener('click', function (e) {
        e.stopPropagation();
        menu.classList.toggle('buka');
      });
      document.addEventListener('click', function () { menu.classList.remove('buka'); });
      menu.addEventListener('click', function () { menu.classList.remove('buka'); });
    }
  });
})();
